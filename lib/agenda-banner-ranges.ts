/**
 * Find the banner that matches a given post slug and date.
 * 1. Check repeatingSlugDateRanges first (slug-based matching)
 * 2. Then check publishStartAt/publishEndAt (date-based matching)
 * 3. Falls back to the current week banner (today)
 */
export function findAgendaBannerForPost(
  slug: string,
  publishStartAt?: string | null,
  publishEndAt?: string | null,
): AgendaBannerRange | undefined {
  const todayKey = new Date().toISOString().slice(0, 10);
  const normalizedSlug = slug.trim().toLowerCase();

  // 1. Check repeating slug date ranges
  const matchRange = repeatingSlugDateRanges.find(
    (r) => r.slug === normalizedSlug && todayKey >= r.from && todayKey <= r.to,
  );
  if (matchRange) {
    // Find the banner range that contains today
    return agendaBannerRanges.find(
      (range) => todayKey >= range.start && todayKey <= range.end,
    );
  }

  // 2. Fall back to publishStartAt / publishEndAt
  const dateStr = publishStartAt || publishEndAt;
  if (dateStr) {
    const key = dateStr.slice(0, 10);
    return agendaBannerRanges.find(
      (range) => key >= range.start && key <= range.end,
    );
  }

  // 3. Default to current week
  return agendaBannerRanges.find(
    (range) => todayKey >= range.start && todayKey <= range.end,
  );
}
